/**
 * Returns the slug to use for a custom role at a given scope.
 * Backend RolePermission.role enum requires one of the *_CUSTOM values for custom roles.
 */
export function getCustomRoleSlugForScope(scope: ScopeCode): RoleSlug {
  switch (scope) {
    case ROLE_SCOPE.PLATFORM:
      return ROLES.PLATFORM_CUSTOM;
    case ROLE_SCOPE.WORKSPACE:
      return ROLES.WORKSPACE_CUSTOM;
    case ROLE_SCOPE.PROJECT:
      return ROLES.PROJECT_CUSTOM;
    case ROLE_SCOPE.TEAM:
      return ROLES.TEAM_CUSTOM;
    case ROLE_SCOPE.HRM:
      return ROLES.HR_CUSTOM;
    case ROLE_SCOPE.ORGANIZATION:
    case ROLE_SCOPE.GUEST:
    default:
      return ROLES.ORG_CUSTOM;
  }
}

