/** Quick lookup whether a role slug is a system-managed (non-custom) role */
export function isSystemRoleSlug(slug: string): boolean {
  const customs: string[] = [
    ROLES.PLATFORM_CUSTOM,
    ROLES.ORG_CUSTOM,
    ROLES.WORKSPACE_CUSTOM,
    ROLES.PROJECT_CUSTOM,
    ROLES.TEAM_CUSTOM,
    ROLES.HR_CUSTOM,
  ];
  return !customs.includes(slug);
}

